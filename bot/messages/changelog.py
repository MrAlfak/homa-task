def build_changelog_announcement(*, bot_name: str = "Team Management Homa") -> str:
    """HTML changelog message for private broadcast to bot users."""
    lines = "\n".join(f"• {item}" for item in CHANGELOG_ITEMS)
    return (
        f"🎉 <b>بروزرسانی ربات {_esc(bot_name, quote=False)}</b>\n\n"
        "سلام 👋\n\n"
        "از صبر و شکیبایی شما در این مدت صمیمانه تشکر می‌کنیم. "
        "ربات مدیریت تسک با بهبودهای زیر به‌روزرسانی شد:\n\n"
        f"{lines}\n\n"
        "برای دیدن منوی جدید یک‌بار <b>/start</b> بزنید.\n\n"
        "اگر سوالی بود، همین‌جا بپرسید. 🙏"
    )


def build_group_announcement(*, bot_name: str = "Team Management Homa") -> str:
    """Backward-compatible alias."""
    return build_changelog_announcement(bot_name=bot_name)
